/** An ASCII STL from boxes given as [min, max] corners. */
function boxesStl(boxes: Array<[number[], number[]]>): string {
	const facets: string[] = []
	for (const [[x0, y0, z0], [x1, y1, z1]] of boxes) {
		const c = [[x0, y0, z0], [x1, y0, z0], [x1, y1, z0], [x0, y1, z0], [x0, y0, z1], [x1, y0, z1], [x1, y1, z1], [x0, y1, z1]]
		const quads = [[0, 3, 2, 1], [4, 5, 6, 7], [0, 1, 5, 4], [1, 2, 6, 5], [2, 3, 7, 6], [3, 0, 4, 7]]
		for (const [a, b, d, e] of quads) {
			for (const triangle of [[a, b, d], [a, d, e]]) {
				facets.push(['facet normal 0 0 0', 'outer loop', ...triangle.map((i) => `vertex ${c[i].join(' ')}`), 'endloop', 'endfacet'].join('\n'))
			}
		}
	}
	return ['solid boxes', ...facets, 'endsolid boxes'].join('\n')
}

/** A binary STL sphere of `rings × segments × 2` triangles: a big model for the worker. */
function bigSphereStl(rings: number, segments: number): Buffer {
	const point = (r: number, s: number) => {
		const theta = (r / rings) * Math.PI
		const phi = (s / segments) * Math.PI * 2
		return [20 * Math.sin(theta) * Math.cos(phi), 20 * Math.cos(theta), 20 * Math.sin(theta) * Math.sin(phi)]
	}
	const triangles: number[][][] = []
	for (let r = 0; r < rings; r++) {
		for (let s = 0; s < segments; s++) {
			const a = point(r, s)
			const b = point(r + 1, s)
			const c = point(r + 1, s + 1)
			const d = point(r, s + 1)
			triangles.push([a, b, c], [a, c, d])
		}
	}
	const buffer = Buffer.alloc(84 + triangles.length * 50)
	buffer.writeUInt32LE(triangles.length, 80)
	triangles.forEach((triangle, i) => {
		const offset = 84 + i * 50 + 12
		triangle.flat().forEach((value, j) => buffer.writeFloatLE(value, offset + j * 4))
	})
	return buffer
}

const PRUSA_GCODE = [
	'; generated by PrusaSlicer 2.8.1+win64 on 2024-09-30 at 10:00:00 UTC',
	'G1 Z0.2 F600', 'G1 X0 Y0 E0', 'G1 X10 Y0 E1', 'G1 X10 Y10 E2',
	'; filament used [mm] = 1520.35',
	'; filament used [g] = 4.54',
	'; estimated printing time (normal mode) = 1h 2m 3s',
].join('\n')

const MODELS = {
	cube: { id: 6161, name: 'cube.stl', body: boxesStl([[[0, 0, 0], [10, 10, 10]]]) },
	// An STL is Z-up: a stem 10 high with a bar across its top, whose undersides overhang
	tee: { id: 6262, name: 'tee.stl', body: boxesStl([[[4, 0, 0], [6, 2, 10]], [[0, 0, 10], [10, 2, 12]]]) },
	slab: { id: 6363, name: 'slab.stl', body: boxesStl([[[0, 0, 0], [20, 0.5, 20]]]) },
	gcode: { id: 6464, name: 'print.gcode', body: PRUSA_GCODE },
	big: { id: 6565, name: 'sphere.stl', body: bigSphereStl(400, 300) },
}

let server: { url: string, close: () => Promise<void> }
test.beforeAll(async () => { server = await startServer() })
test.afterAll(async () => { await server.close() })

const panelButton = (page: Page) => page.locator('.slide-out-panel').getByRole('button', { name: /^Print check/ })
const card = (page: Page) => page.locator('.print-check-card')

async function openPrintCheck(page: Page, model: keyof typeof MODELS) {
	// Settings are read once from the server; unanswered, the viewer uses its defaults
	await page.route('**/apps/threedviewer/settings', (route) => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ settings: {} }) }))
	const { errors } = await openViewer(page, server.url, MODELS[model])
	await panelButton(page).click()
	await expect(card(page)).toBeVisible()
	return { errors }
}

test('a 10 mm cube fits, and a 5 mm custom printer reports 5 mm too wide, deep and tall', async ({ page }) => {
	const { errors } = await openPrintCheck(page, 'cube')
	await expect(card(page)).toContainText('Fits the build volume')
	await expect(card(page)).toContainText("Sizes assume millimetres, because this file doesn't record a unit.")

	await card(page).locator('#print-check-printer').selectOption('custom')
	for (const side of ['width', 'depth', 'height']) {
		await card(page).locator(`#print-check-${side}`).fill('5')
		await card(page).locator(`#print-check-${side}`).dispatchEvent('change')
	}
	await expect(card(page)).toContainText('5 mm too wide')
	await expect(card(page)).toContainText('5 mm too deep')
	await expect(card(page)).toContainText('5 mm too tall')
	await expect(panelButton(page)).toHaveAttribute('aria-pressed', 'true')
	expect(errors).toEqual([])
})

