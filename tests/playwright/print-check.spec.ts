/** An ASCII STL from boxes given as [min, max] corners. */
function boxesStl(boxes: Array<[number[], number[]]>): string {
	const facets: string[] = []
	for (const [[x0, y0, z0], [x1, y1, z1]] of boxes) {
		const c = [[x0, y0, z0], [x1, y0, z0], [x1, y1, z0], [x0, y1, z0], [x0, y0, z1], [x1, y0, z1], [x1, y1, z1], [x0, y1, z1]]
		const quads = [[0, 3, 2, 1], [4, 5, 6, 7], [0, 1, 5, 4], [1, 2, 6, 5], [2, 3, 7, 6], [3, 0, 4, 7]]
		for (const [a, b, d, e] of quads) {
			for (const triangle of [[a, b, d], [a, d, e]]) {
				facets.push(['facet normal 0 0 0', 'outer loop', ...triangle.map((i) => `vertex ${c[i].join(' ')}`), 'endloop', 'endfacet'].join('\n'))
			}
		}
	}
	return ['solid boxes', ...facets, 'endsolid boxes'].join('\n')
}

/** A binary STL sphere of `rings × segments × 2` triangles: a big model for the worker. */
function bigSphereStl(rings: number, segments: number): Buffer {
	const point = (r: number, s: number) => {
		const theta = (r / rings) * Math.PI
		const phi = (s / segments) * Math.PI * 2
		return [20 * Math.sin(theta) * Math.cos(phi), 20 * Math.cos(theta), 20 * Math.sin(theta) * Math.sin(phi)]
	}
	const triangles: number[][][] = []
	for (let r = 0; r < rings; r++) {
		for (let s = 0; s < segments; s++) {
			const a = point(r, s)
			const b = point(r + 1, s)
			const c = point(r + 1, s + 1)
			const d = point(r, s + 1)
			triangles.push([a, b, c], [a, c, d])
		}
	}
	const buffer = Buffer.alloc(84 + triangles.length * 50)
	buffer.writeUInt32LE(triangles.length, 80)
	triangles.forEach((triangle, i) => {
		const offset = 84 + i * 50 + 12
		triangle.flat().forEach((value, j) => buffer.writeFloatLE(value, offset + j * 4))
	})
	return buffer
}

