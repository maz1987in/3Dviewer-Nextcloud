/**
 * The print time and filament a slicer wrote into a G-code file's comments. Each slicer
 * writes them its own way, and PrusaSlicer at the very end of the file.
 */
import { parseSlicerSummary, parseDuration, findSlicerSummary } from '../../../src/printCheck/slicerSummary.js'
import { formatDuration } from '../../../src/printCheck/formatDuration.js'
import GCodeLoader from '../../../src/loaders/types/gcode.js'
import * as THREE from 'three'

jest.mock('@nextcloud/l10n', () => ({
	translate: (_app, text, vars = {}) => text.replace(/{(\w+)}/g, (_, key) => String(vars[key])),
}))

const MOVES = 'G1 Z0.2 F600\nG1 X0 Y0 E0\nG1 X10 Y0 E1\n'
const PRUSA_FOOTER = [
	'; filament used [mm] = 1520.35',
	'; filament used [cm3] = 3.66',
	'; filament used [g] = 4.54',
	'; estimated printing time (normal mode) = 1h 2m 3s',
].join('\n')

test('PrusaSlicer: name at the top, numbers at the end', () => {
	const text = `; generated by PrusaSlicer 2.8.1+win64 on 2024-09-30 at 10:00:00 UTC\n${MOVES}${PRUSA_FOOTER}\n`
	expect(parseSlicerSummary(text)).toEqual({ slicer: 'PrusaSlicer 2.8.1', printSeconds: 3723, filamentMm: 1520.35, filamentGrams: 4.54 })
})

test('SuperSlicer writes as PrusaSlicer does', () => {
	const text = `; generated by SuperSlicer 2.5.59.13 on 2024-09-30 at 10:00:00 UTC\n${MOVES}${PRUSA_FOOTER}\n`
	expect(parseSlicerSummary(text).slicer).toBe('SuperSlicer 2.5.59.13')
	expect(parseSlicerSummary(text).printSeconds).toBe(3723)
})

test('OrcaSlicer: the total estimated time beats the model printing time', () => {
	const text = [
		'; generated by OrcaSlicer 2.1.1 on 2024-09-30 at 10:00:00',
		'; model printing time: 52m 10s; total estimated time: 58m 41s',
		'; total filament length [mm] : 1520.35',
		'; total filament weight [g] : 4.54',
		MOVES,
	].join('\n')
	expect(parseSlicerSummary(text)).toEqual({ slicer: 'OrcaSlicer 2.1.1', printSeconds: 3521, filamentMm: 1520.35, filamentGrams: 4.54 })
})

test('Bambu Studio: its header block', () => {
	const text = [
		'; HEADER_BLOCK_START',
		'; BambuStudio 01.09.07.52',
		'; model printing time: 1h 2m 3s; total estimated time: 1h 8m 9s',
		'; total layer number: 50',
		'; total filament length [mm] : 1520.35',
		'; total filament volume [cm^3] : 3657.04',
		'; total filament weight [g] : 4.54',
		'; HEADER_BLOCK_END',
		MOVES,
	].join('\n')
	expect(parseSlicerSummary(text)).toEqual({ slicer: 'BambuStudio 01.09.07.52', printSeconds: 4089, filamentMm: 1520.35, filamentGrams: 4.54 })
})

test('Cura: seconds and metres, no weight', () => {
	const text = [';FLAVOR:Marlin', ';TIME:3723', ';Filament used: 1.52035m', ';Layer height: 0.2', ';Generated with Cura_SteamEngine 5.7.1', MOVES].join('\n')
	expect(parseSlicerSummary(text)).toEqual({ slicer: 'Cura 5.7.1', printSeconds: 3723, filamentMm: 1520.35, filamentGrams: null })
})

test('no comments: every field is null', () => {
	expect(parseSlicerSummary(MOVES)).toEqual({ slicer: null, printSeconds: null, filamentMm: null, filamentGrams: null })
})

test('footer only: a 2 MB file with the PrusaSlicer footer at the very end is still found', () => {
	const body = 'G1 X1 Y1 E1\n'.repeat(Math.ceil(2 * 1024 * 1024 / 12))
	const result = parseSlicerSummary(`${body}${PRUSA_FOOTER}\n`)
	expect(result.printSeconds).toBe(3723)
	expect(result.filamentGrams).toBe(4.54)
})

test('parseDuration reads days, hours, minutes and seconds', () => {
	expect(parseDuration('1d 2h 3m 4s')).toBe(93784)
	expect(parseDuration('58m 41s')).toBe(3521)
	expect(parseDuration('45s')).toBe(45)
	expect(parseDuration('soon')).toBeNull()
})

test('formatDuration reads as a person would say it', () => {
	expect(formatDuration(3723)).toBe('1 h 2 min')
	expect(formatDuration(3521)).toBe('58 min')
	expect(formatDuration(45)).toBe('45 s')
	expect(formatDuration(93784)).toBe('1 d 2 h')
})

test('findSlicerSummary finds it under the model', () => {
	const root = new THREE.Group()
	const group = new THREE.Group()
	group.userData.slicerSummary = { slicer: 'Cura 5.7.1', printSeconds: 1, filamentMm: null, filamentGrams: null }
	root.add(group)
	expect(findSlicerSummary(root)).toBe(group.userData.slicerSummary)
	expect(findSlicerSummary(new THREE.Group())).toBeNull()
})

test('the G-code loader keeps the summary on the model it returns', async () => {
	const text = `; generated by PrusaSlicer 2.8.1+win64 on 2024-09-30 at 10:00:00 UTC\n${MOVES}${PRUSA_FOOTER}\n`
	const { object3D } = await new GCodeLoader().loadModel(new TextEncoder().encode(text).buffer, {})
	expect(findSlicerSummary(object3D)).toEqual({ slicer: 'PrusaSlicer 2.8.1', printSeconds: 3723, filamentMm: 1520.35, filamentGrams: 4.54 })
})

test('a crafted comment line of digits does not stall the parser', () => {
	const digits = '9'.repeat(200000)
	const text = `; estimated printing time (normal mode) = ${digits}\n; total estimated time: ${digits}\n${PRUSA_FOOTER}\n`
	const started = Date.now()
	const result = parseSlicerSummary(text)
	expect(Date.now() - started).toBeLessThan(500)
	expect(result.filamentGrams).toBe(4.54)
	const startedDuration = Date.now()
	expect(parseDuration(digits)).toBeNull()
	expect(Date.now() - startedDuration).toBeLessThan(500)
})
