/**
 * Regenerate `src/config/icon-paths.js` from vue-material-design-icons.
 *
 * The viewer needs about thirty icons across the redesigned panels. Importing each as its
 * own component costs roughly 0.95 KB raw apiece once compiled — ten of them put the app
 * chunk over its budget on their own — and every one of those kilobytes is a Vue render
 * function wrapping a single `<path>`. The path alone is a few hundred bytes.
 *
 * So the paths are extracted here and rendered by one shared component. The package stays
 * the source: nothing is transcribed by hand, and `tests/unit/iconPaths.test.js` compares
 * every entry back against it, so an upstream icon change shows up as a failing test
 * rather than as a shape that quietly stops matching the rest of Nextcloud's iconography.
 *
 * Run with `npm run icons:sync` after adding a name to ICONS below.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

/** Icon name in this app → component file in the package. */
export const ICONS = {
	animationPause: 'Pause',
	animationPlay: 'Play',
	camera: 'Camera',
	controller: 'Gamepad',
	fitToView: 'Fullscreen',
	help: 'HelpCircle',
	palette: 'Palette',
	resetView: 'Refresh',
	tools: 'Tune',
	vr: 'Glasses',
}

const PACKAGE = resolve(process.cwd(), 'node_modules/vue-material-design-icons')

/**
 * The `d` attribute of a package icon's single path.
 *
 * @param {string} component - component file name without extension
 * @return {string} the path data
 */
export function pathOf(component) {
	const source = readFileSync(resolve(PACKAGE, `${component}.vue`), 'utf8')
	const paths = [...source.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1])
	if (paths.length !== 1) {
		throw new Error(`${component}.vue has ${paths.length} paths; expected exactly 1`)
	}
	return paths[0]
}

const entries = Object.entries(ICONS)
	.sort(([a], [b]) => a.localeCompare(b))
	.map(([name, component]) => `\t${name}: '${pathOf(component)}',`)
	.join('\n')

const file = `/**
 * Material Design icon paths, extracted from vue-material-design-icons.
 *
 * Generated by \`npm run icons:sync\` — do not edit by hand. Add a name to the ICONS map in
 * \`scripts/sync-icon-paths.mjs\` and re-run it. The paths are copied rather than imported
 * because a compiled icon component costs about 0.95 KB raw where its path costs a few
 * hundred bytes, and the redesign needs roughly thirty of them.
 *
 * A copy that nothing compares against drifts, so \`tests/unit/iconPaths.test.js\` checks
 * every entry back against the package.
 */
export const ICON_PATHS = {
${entries}
}
`

writeFileSync(resolve(process.cwd(), 'src/config/icon-paths.js'), file)
// eslint-disable-next-line no-console
console.log(`[icons] wrote ${entries.split('\n').length} paths to src/config/icon-paths.js`)
